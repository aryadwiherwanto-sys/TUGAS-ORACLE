public class Nomor1 {
    public static void main(String[] args) {
        int x = 6;

        // Ternary: jika x <= 7 hasilnya true, selain itu false
        boolean status = x <= 7 ? true : false;

        System.out.println("Nilai x: " + x);
        System.out.println("Hasil kondisi: " + status);
    }
}
